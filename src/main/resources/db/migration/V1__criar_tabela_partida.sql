-- SQL padrão, compatível com PostgreSQL (produção) e H2 (desenvolvimento e testes).
create table partida (
    id                bigint generated by default as identity primary key,
    id_externo        varchar(100) not null,
    codigo_competicao varchar(20)  not null,
    temporada         integer      not null,
    rodada            integer      not null,
    data_hora         timestamp with time zone not null,
    mandante          varchar(150) not null,
    visitante         varchar(150) not null,
    status            varchar(20)  not null,
    gols_mandante     integer,
    gols_visitante    integer,
    constraint uk_partida_id_externo unique (id_externo)
);

create index ix_partida_competicao on partida (codigo_competicao, temporada, data_hora);
